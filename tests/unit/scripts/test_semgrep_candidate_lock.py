import hashlib
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from scripts import candidate_runner as runner


class RenamedLockContract(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.wheel = self.root / "specfact_semgrep-1.179.0.post1-py3-none-any.whl"
        self.wheel.write_bytes(b"inert unit fixture")
        self.digest = hashlib.sha256(self.wheel.read_bytes()).hexdigest()
        self.locked = self.root / "compiled.txt"
        self.output = self.root / "flat.txt"
        self.actual = {"specfact-semgrep": "1.179.0.post1", "mcp": "1.30.0"}
        self.dependency = "mcp==1.30.0 --hash=sha256:" + "a" * 64 + "\n"

    def test_direct_candidate_wheel_is_hash_bound_with_all_dependencies(self) -> None:
        self.locked.write_text(
            f"specfact-semgrep @ {self.wheel.as_uri()} --hash=sha256:{self.digest}\n" + self.dependency
        )
        runner._flat_lock(self.locked, self.actual, self.wheel, self.output)
        self.assertEqual(
            self.output.read_text(),
            self.dependency + f"specfact-semgrep==1.179.0.post1 --hash=sha256:{self.digest}\n",
        )

    def test_uv_bare_candidate_path_with_continuations_and_comments(self) -> None:
        for newline in ("\n", "\r\n"):
            with self.subTest(newline=repr(newline)):
                self.locked.write_bytes(
                    (
                        "# This file was autogenerated by uv\n"
                        + self.dependency
                        + f"{self.wheel} \\\n    --hash=sha256:{self.digest}\n"
                        + "    # via -r candidate.in\n"
                    )
                    .replace("\n", newline)
                    .encode()
                )
                runner._flat_lock(self.locked, self.actual, self.wheel, self.output)
                self.assertEqual(
                    self.output.read_text(),
                    self.dependency + f"specfact-semgrep==1.179.0.post1 --hash=sha256:{self.digest}\n",
                )

    def test_uv_windows_bare_path_preserves_backslashes(self) -> None:
        wheel = Path(r"D:\a\_temp\canonical\wheels\specfact_semgrep-1.179.0.post1-py3-none-win_amd64.whl")
        self.locked.write_text(f"{wheel} \\\n    --hash=sha256:{self.digest}\n" + self.dependency)
        with patch.object(runner, "_digest", return_value=self.digest):
            runner._flat_lock(self.locked, self.actual, wheel, self.output)
        self.assertEqual(
            self.output.read_text(),
            self.dependency + f"specfact-semgrep==1.179.0.post1 --hash=sha256:{self.digest}\n",
        )

    def test_rejects_wrong_candidate_target_even_with_exact_hash(self) -> None:
        other = self.root / "other" / self.wheel.name
        for target in (
            str(other),
            f"specfact-semgrep @ {other.as_uri()}",
            f"specfact-semgrep @ https://example.com/{self.wheel.name}",
        ):
            with self.subTest(target=target):
                self.locked.write_text(f"{target} --hash=sha256:{self.digest}\n" + self.dependency)
                with self.assertRaises(ValueError):
                    runner._flat_lock(self.locked, self.actual, self.wheel, self.output)

    def test_rejects_missing_wrong_or_additional_candidate_hash(self) -> None:
        for tail in ("", " --hash=sha256:" + "b" * 64, f" --hash=sha256:{self.digest} --hash=sha256:" + "b" * 64):
            with self.subTest(tail=tail):
                self.locked.write_text(f"specfact-semgrep @ {self.wheel.as_uri()}{tail}\n" + self.dependency)
                with self.assertRaises(ValueError):
                    runner._flat_lock(self.locked, self.actual, self.wheel, self.output)

    def test_rejects_duplicate_candidate_or_unrecognized_extra_requirement(self) -> None:
        candidate = f"specfact-semgrep @ {self.wheel.as_uri()} --hash=sha256:{self.digest}\n"
        for extra in (
            candidate,
            f"{self.wheel} --hash=sha256:{self.digest}\n",
            "unexpected @ file:///other.whl --hash=sha256:" + "b" * 64 + "\n",
        ):
            with self.subTest(extra=extra):
                self.locked.write_text(candidate + self.dependency + extra)
                with self.assertRaises(ValueError):
                    runner._flat_lock(self.locked, self.actual, self.wheel, self.output)

    def test_preserves_dependency_identity_version_and_hash_coverage(self) -> None:
        for dependency in (
            "",
            "mcp==1.30.0\n",
            self.dependency.replace("1.30.0", "1.29.0"),
            self.dependency * 2,
            self.dependency + "unexpected==1.0 --hash=sha256:" + "b" * 64 + "\n",
        ):
            with self.subTest(dependency=dependency):
                self.locked.write_text(
                    f"specfact-semgrep @ {self.wheel.as_uri()} --hash=sha256:{self.digest}\n" + dependency
                )
                with self.assertRaises(ValueError):
                    runner._flat_lock(self.locked, self.actual, self.wheel, self.output)


if __name__ == "__main__":
    unittest.main()
